from dataclasses import dataclass

from app.services.chunking import Chunk, create_chunks
from app.services.documents import ParsedDocument


@dataclass
class PreparedChunk:
    text: str
    chunk_index: int
    chunk_level: str
    parent_chunk_index: int | None
    page_number: int | None
    section: str | None
    subsection: str | None
    content_hash: str


def prepare_document_chunks(
    document: ParsedDocument,
    chunk_size: int = 1200,
    overlap: int = 200,
    parent_size: int = 3000,
) -> list[PreparedChunk]:
    """
    Convert a parsed document into retrieval-ready chunks.

    Each page is processed independently so chunks do not
    accidentally cross page boundaries.

    Parent/child relationships generated by the chunker
    are converted from page-local indexes into global
    document-level indexes.
    """

    prepared_chunks: list[PreparedChunk] = []

    global_chunk_index = 0

    for page in document.pages:

        if not page.text.strip():
            continue

        page_chunks: list[Chunk] = create_chunks(
            text=page.text,
            chunk_size=chunk_size,
            overlap=overlap,
            parent_size=parent_size,
        )

        local_to_global: dict[int, int] = {}

        # First pass:
        # assign every local chunk its global index.
        for chunk in page_chunks:
            local_to_global[
                chunk.chunk_index
            ] = global_chunk_index

            global_chunk_index += 1

        # Second pass:
        # resolve local parent indexes to global indexes.
        for chunk in page_chunks:

            parent_chunk_index = None

            if chunk.parent_chunk_index is not None:
                parent_chunk_index = local_to_global.get(
                    chunk.parent_chunk_index
                )

                if parent_chunk_index is None:
                    raise RuntimeError(
                        "Unable to resolve parent chunk "
                        f"{chunk.parent_chunk_index} "
                        f"for chunk {chunk.chunk_index}."
                    )

            prepared_chunks.append(
                PreparedChunk(
                    text=chunk.text,
                    chunk_index=local_to_global[
                        chunk.chunk_index
                    ],
                    chunk_level=chunk.chunk_level,
                    parent_chunk_index=parent_chunk_index,
                    page_number=page.page_number,
                    section=chunk.section,
                    subsection=chunk.subsection,
                    content_hash=chunk.content_hash,
                )
            )

    return prepared_chunks